-- Which muscles each exercise trains, for the muscle map. PRIMARY counts a set as 1 for the muscle, SECONDARY
-- as 0.5. Custom exercises have no rows: the app derives their muscles from muscle_group instead.
-- ADDUCTORS and ABDUCTORS are stored for accuracy and folded into QUADS / GLUTES when the map is drawn.
CREATE TABLE exercise_muscles (
    exercise_id BIGINT      NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
    muscle      VARCHAR(16) NOT NULL CHECK (muscle IN
        ('CHEST', 'FRONT_DELTS', 'SIDE_DELTS', 'REAR_DELTS', 'BICEPS', 'TRICEPS', 'FOREARMS', 'ABS', 'OBLIQUES',
         'TRAPS', 'LATS', 'LOWER_BACK', 'GLUTES', 'QUADS', 'HAMSTRINGS', 'CALVES', 'ADDUCTORS', 'ABDUCTORS')),
    role        VARCHAR(10) NOT NULL CHECK (role IN ('PRIMARY', 'SECONDARY')),
    PRIMARY KEY (exercise_id, muscle)
);

